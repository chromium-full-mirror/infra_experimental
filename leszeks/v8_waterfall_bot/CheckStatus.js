const fetch = require('node-fetch');
const {BigQuery} = require('@google-cloud/bigquery');

const CHAT_URL = 'https://chat.googleapis.com/v1/spaces/AAAAy3GcQSI/messages?key=KEY&token=TOKEN'
const TREE_URL = 'https://v8-status.appspot.com/current?format=json'

const REVIEW_HOST = 'https://chromium-review.googlesource.com'
const ROLL_ACCOUNT = 'chromium-autoroll@skia-public.iam.gserviceaccount.com'
const QUERY_PARAM = `q=owner:${ROLL_ACCOUNT}+project:chromium/src+subject:"Roll+v8+from"`
const QUERY_OPTIONS = 'o=MESSAGES&o=CURRENT_REVISION&o=CURRENT_COMMIT'
const ROLL_URL = `${REVIEW_HOST}/changes/?${QUERY_PARAM}&n=1&${QUERY_OPTIONS}`

const BIG_QUERY = new BigQuery();

async function getSavedStatus() {
  const query = `
    SELECT data
    FROM \`google.com:v8-waterfall-bot.rollstatus.status\`
    LIMIT 1
  `;
  const [rows] = await BIG_QUERY.query(query);
  return JSON.parse(rows[0].data);
}

async function saveStatus(data) {
  const query = `
    UPDATE \`google.com:v8-waterfall-bot.rollstatus.status\`
    SET data=@data
    WHERE true
  `;
  await BIG_QUERY.query({
    query,
    params: {
      data: JSON.stringify(data)
    }
  });
}

async function fetchTreeStatus() {
  const response = await fetch(TREE_URL);
  return await response.json();
}

function countRollAttempts(content, failure_i) {
  let attempts = 0;
  for (let i = failure_i; i >=0; --i) {
    const msg = content.messages[i];
    if (msg.message?.includes("CQ is trying the patch")) {
      attempts++;
    } else if (msg.message?.includes("CV is trying the patch")) {
      attempts++;
    }
  }
  return attempts
}

async function fetchRollStatus() {
  const response = await fetch(ROLL_URL);
  const text = await response.text();
  const content = JSON.parse(text.substring(text.indexOf('\n')))[0];

  const roll_state = {
    date: null,
    msg: null,
    status: null,
    version: null,
    number: null
  };

  for (let i = content.messages.length - 1; i >=0; --i) {
    const msg = content.messages[i];

    const tag = msg['tag'] ?? '';
    const message = msg['message'] ?? '<No message>';

    if (message.includes("CQ is trying the patch")) {
      continue;
    } else if (message.includes("CV is trying the patch")) {
      continue;
    } else if (message.includes("This CL passed the CQ dry run")) {
      continue;
    } else if (message.includes("This CL has passed the run")) {
      continue;
    } else if (tag.includes("autogenerated:gerrit:newPatchSet")) {
      roll_state.status = "New Roll";
    } else if (tag.includes("autogenerated:gerrit:merged")) {
      roll_state.status = "Merged";
    } else if (tag.includes("abandon")) {
      roll_state.status = "Abandoned";
    } else if (message.includes("-Commit-Queue")) {
      continue;
    } else if (message.includes("Commit-Queue+2")) {
      continue;
    } else if (message.includes("Code-Review+1")) {
      continue;
    } else if (message.includes("who was added as reviewer owns the following files")) {
      continue;
    } else {
      const attempts = countRollAttempts(content, i)
      roll_state.status = `Failed (${attempts} attempt${attempts != 1 ? 's' : ''})`;
    }

    roll_state.msg = message
    roll_state.date = msg.date;
    break;
  }

  roll_state.number = content._number;
  const commit_message = content.revisions[content.current_revision].commit.message;
  roll_state.version = commit_message.match(/ Version (\d+\.\d+\.\d+(?:\.\d+)?)/)?.[1] ?? "Unknown";

  return roll_state
}

async function sendTextMessage(text, thread=undefined) {
  const body = { text };
  if (thread) {
    body.thread = thread;
  }
  const ret = await fetch(CHAT_URL, {
    method: 'POST',
    headers: { 'Content-Type': 'application/json; charset=UTF-8' },
    body: JSON.stringify(body),
  });
  return (await ret.json()).thread;
}

/**
 * Triggered from a message on a Cloud Pub/Sub topic.
 *
 * @param {!Object} event Event payload.
 * @param {!Object} context Metadata for the event.
 */
exports.onMessage = async (event, context) => {
  const data = event.data
    ? Buffer.from(event.data, 'base64').toString()
    : null;

  const current_status_promise = getSavedStatus();
  const roll_status_promise = fetchRollStatus();
  const tree_status_promise = fetchTreeStatus();

  const current_status = await current_status_promise;

  let status_changed = false;

  const roll_status = await roll_status_promise;
  let roll_thread = current_status.roll_thread;
  if (roll_status.date !== current_status.roll_status?.date) {
    status_changed = true;
    console.log(roll_status);

    let roll_text = "";
    if (roll_status.status == "New Roll" || roll_status.status == "Merged") {
      roll_text += "✅ ";
    } else {
      roll_text += "❌ ";
    }
    roll_text += `*Roll ${roll_status.version}: ${roll_status.status}*\n_${roll_status.date}_ — https://crrev.com/c/${roll_status.number}`;
    if (roll_status.status != "New Roll") {
      roll_text += "\n" + roll_status.msg;
    }
    roll_thread = await sendTextMessage(roll_text, roll_thread);
  }

  const tree_status = await tree_status_promise;
  let tree_thread = current_status.tree_thread;
  if (tree_status.date !== current_status.tree_status?.date) {
    status_changed = true;
    console.log(tree_status);

    let tree_text = "";
    if (tree_status.general_state == "open") {
      tree_text += "✅ ";
    } else {
      tree_text += "❌ ";
    }
    tree_text += `*Tree: ${tree_status.general_state == "open" ? tree_status.message : tree_status.general_state}*\n_${tree_status.date}_`;
    if (tree_status.general_state != "open") {
      tree_text = tree_text + "\n" + tree_status.message + "\nSee tree status: http://v8-status.appspot.com/";
    }
    tree_thread = await sendTextMessage(tree_text, tree_thread);
  }

  if (status_changed) {
    await saveStatus({
      roll_thread,
      roll_status,
      tree_thread,
      tree_status,
    });
  }
};
